export function localizeAnimal(animal: AnimalRecord, language: Language): AnimalRecord {
  if (language === "en") return animal;
  const translated = spanish[animal.id] ?? {};
  return {
    ...animal,
    name: translated.name ?? animal.name,
    habitat: translated.habitat ?? optionLabel(animal.habitat, language),
    fact: translated.fact ?? animal.fact,
    group: translated.group ?? optionLabel(animal.group, language),
    region: translated.region ?? optionLabel(animal.region, language),
    adaptation: translated.adaptation ?? animal.adaptation,
  };
}
